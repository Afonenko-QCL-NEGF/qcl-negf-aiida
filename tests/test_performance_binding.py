def test_missing_or_rejected_performance_is_unavailable_without_scientific_exit_change(typed):
    class Outputs(dict):
        def __getattr__(self,key):
            try:return self[key]
            except KeyError as error:raise AttributeError(key) from error
    child=NS(outputs=Outputs())
